def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 22), b""):
            h.update(block)
    return h.hexdigest()


def shard_url(name: str) -> str:
    return f"https://huggingface.co/datasets/{DATASET_ID}/resolve/{DATASET_REVISION}/{name}"


def download(url: str, dest: Path, sha256: str, size: int | None = None) -> None:
    if dest.exists() and (size is None or dest.stat().st_size == size) and sha256_file(dest) == sha256:
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_name(dest.name + ".part")
    print(f"downloading {url}", flush=True)
    with urllib.request.urlopen(url, timeout=120) as r, open(part, "wb") as f:
        while block := r.read(1 << 22):
            f.write(block)
    got = sha256_file(part)
    if got != sha256:
        part.unlink()
        raise SystemExit(f"sha256 mismatch for {url}: {got} != {sha256}")
    os.replace(part, dest)


# ---------------------------------------------------------------- normalization

def near_key(text: str) -> str:
    kept = [ln for ln in text.split("\n") if not ln.lstrip().startswith("#")]
    return sha256_bytes(WS_RE.sub("", "\n".join(kept)).encode("utf-8"))


def squash(text: str) -> str:
    return WS_RE.sub("", text)


# ---------------------------------------------------------------- decontamination

def load_blocklist(cache: Path) -> list[dict]:
    """Every text we must not train on, tagged with its source."""
    items: list[dict] = []

    def add(source: str, ref: str, text: str) -> None:
        text = text.replace("\r\n", "\n").replace("\r", "\n")
        if text.strip():
            items.append({"source": source, "ref": ref, "text": text})

    with gzip.open(cache / "benchmarks" / "HumanEval.jsonl.gz", "rt", encoding="utf-8") as f:
        for line in f:
            t = json.loads(line)
            tid = t["task_id"]
            add("humaneval", f"{tid}/prompt", t["prompt"])
            add("humaneval", f"{tid}/prompt+solution", t["prompt"] + t["canonical_solution"])
            add("humaneval", f"{tid}/test", t["test"])
            # signature + solution without the docstring catches re-documented copies
            m = re.search(rf"^def {re.escape(t['entry_point'])}\(.*?\).*?:\s*$", t["prompt"], re.M | re.S)
            if m:
                add("humaneval", f"{tid}/def+solution", m.group(0).split("\n")[0] + "\n" + t["canonical_solution"])
    with open(cache / "benchmarks" / "mbpp.jsonl", encoding="utf-8") as f:
        for line in f:
            t = json.loads(line)
            tid = t["task_id"]
            add("mbpp", f"{tid}/text", t["text"])
            add("mbpp", f"{tid}/code", t["code"])
            add("mbpp", f"{tid}/tests", "\n".join(t["test_list"] + t.get("challenge_test_list", [])))
    for rel in PROJECT_TASK_FILES:
        pack = json.loads((ROOT / rel).read_text(encoding="utf-8"))
        for t in pack["tasks"]:
            tid = t["id"]
            add("project_level1", f"{tid}/prompt", t["prompt"])
            for kind in ("files", "reference"):
                for name, text in (t.get(kind) or {}).items():
                    add("project_level1", f"{tid}/{kind}/{name}", text)
            for kind in ("public_check", "private_check"):
                if isinstance(t.get(kind), str):
                    add("project_level1", f"{tid}/{kind}", t[kind])
            for c in t.get("regression_controls") or []:
                if isinstance(c.get("source"), str):
                    add("project_level1", f"{tid}/{c.get('id')}", c["source"])
    for path in sorted((ROOT / PROJECT_CURRICULUM_DIR).glob("*.jsonl")):
        with open(path, encoding="utf-8") as f:
            for line in f:
                t = json.loads(line)
                add("project_curriculum_v2", f"{t['id']}/prompt", t["prompt"])
                add("project_curriculum_v2", f"{t['id']}/completion", t["completion"])
    # identical texts (e.g. repeated curriculum completions) collapse to one item
    seen: dict[str, dict] = {}
    for it in items:
        key = it["text"]
        if key in seen:
            seen[key].setdefault("also", []).append(f"{it['source']}:{it['ref']}")
        else:
            seen[key] = it
    return list(seen.values())


class Decontaminator:
    """Item-relative n-gram containment.

    A document is contaminated by an item when it contains at least
    CONTAM_FRACTION of the item's distinct NGRAM-token n-grams. Project items
    shorter than NGRAM tokens are matched as whitespace-free substrings; short
    HumanEval/MBPP items are too generic to match on and are skipped (counted).
    """

    def __init__(self, items: list[dict]):
        self.items = items
        self.index: dict[tuple, list[int]] = collections.defaultdict(list)
        self.need: list[int] = []
        self.short: list[tuple[int, str]] = []
        self.skipped: list[int] = []
        for i, it in enumerate(items):
            toks = TOKEN_RE.findall(it["text"])
            grams = {tuple(toks[j:j + NGRAM]) for j in range(len(toks) - NGRAM + 1)}
            if grams:
                for g in grams:
                    self.index[g].append(i)
                self.need.append(max(1, math.ceil(CONTAM_FRACTION * len(grams))))
            else:
                self.need.append(0)
                if it["source"].startswith("project"):
                    self.short.append((i, squash(it["text"])))
                else:
                    self.skipped.append(i)

    def hits(self, text: str) -> list[int]:
        toks = TOKEN_RE.findall(text)
        found: dict[int, int] = collections.Counter()
        seen = set()
        index = self.index
        for j in range(len(toks) - NGRAM + 1):
            g = tuple(toks[j:j + NGRAM])
            ids = index.get(g)
            if ids is not None and g not in seen:
                seen.add(g)
                for i in ids:
                    found[i] += 1
        out = [i for i, c in found.items() if c >= self.need[i]]
        if self.short:
            sq = squash(text)
            out.extend(i for i, s in self.short if s in sq)
        return sorted(out)


# ---------------------------------------------------------------- per-file work

def filter_reason(rec: dict, content: str) -> str | None:
    if rec.get("license") not in LICENSES:
        return "license"
    if "�" in content or "\x00" in content:
        return "non_utf8"
    try:
        raw = content.encode("utf-8")
    except UnicodeEncodeError:
        return "non_utf8"
    if len(raw) > MAX_BYTES:
        return "too_large"
    if len(content.strip()) < MIN_STRIPPED_CHARS:
        return "too_small"
    path = rec.get("path", "")
    head = content[:2048].lower()
    if path.endswith(AUTOGEN_PATH_SUFFIXES) or any(m in head for m in AUTOGEN_MARKERS):
        return "autogenerated"
    lines = content.split("\n")
    if max(len(ln) for ln in lines) > MAX_LINE or len(content) / len(lines) > MAX_MEAN_LINE:
        return "minified_or_data"
    if sum(c.isalnum() for c in content) / len(content) < MIN_ALNUM_FRAC:
        return "minified_or_data"
    return None


def parse_py3(content: str):
    try:
        return ast.parse(content)
    except (SyntaxError, ValueError, RecursionError, MemoryError, OverflowError):
        return None


def extract_pairs(tree: ast.Module, content: str) -> list[dict]:
    lines = content.split("\n")
    pairs = []

    def visit(node, prefix):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                qual = f"{prefix}{child.name}"
                if not isinstance(child, ast.ClassDef):
                    p = pair_for(child, qual)
                    if p:
                        pairs.append(p)
                visit(child, qual + ".")

    def pair_for(fn, qual):
        doc = ast.get_docstring(fn, clean=True)
        if not doc or len(doc.strip()) < PAIR_MIN_DOC or len(fn.body) < 2:
            return None
        ds, nxt = fn.body[0], fn.body[1]
        if ds.end_lineno is None or fn.end_lineno is None or nxt.lineno <= ds.end_lineno:
            return None
        if fn.lineno >= ds.lineno:  # docstring on the def line
            return None
        indent = lines[fn.lineno - 1][: fn.col_offset]

        def dedent(ls):
            return "\n".join(ln[len(indent):] if ln.startswith(indent) else ln.lstrip() for ln in ls)

        prompt = dedent(lines[fn.lineno - 1: ds.end_lineno]) + "\n"
        completion = dedent(lines[ds.end_lineno: fn.end_lineno]).rstrip() + "\n"
        if not completion.strip() or len(prompt) > PAIR_MAX_PROMPT or len(completion) > PAIR_MAX_COMPLETION:
            return None
        return {
            "qualname": qual,
            "docstring": doc,
            "prompt": prompt,
            "completion": completion,
            "sha256": sha256_bytes(squash(prompt + completion).encode("utf-8")),
        }

    visit(tree, "")
    return pairs


_DECON: Decontaminator | None = None


def _init_worker(items):
    global _DECON
    _DECON = Decontaminator(items)


def process_chunk(args):
    shard, start, lines = args
    out = []
    for k, line in enumerate(lines):
        rec = json.loads(line)
        content = rec["content"].replace("\r\n", "\n").replace("\r", "\n")
        base = {"id": f"{shard}:{start + k}", "license": rec.get("license"), "bytes": len(rec["content"].encode("utf-8", "surrogatepass"))}
        reason = filter_reason(rec, content)
        tree = None
        if reason is None:
            tree = parse_py3(content)
            if tree is None:
                reason = "not_python3"
        if reason:
            out.append({**base, "drop": reason})
            continue
        raw = content.encode("utf-8")
        out.append({
            **base,
            "bytes": len(raw),
            "repo_name": rec["repo_name"],
            "path": rec["path"],
            "content": content,
            "sha256": sha256_bytes(raw),
            "near": near_key(content),
            "contam": _DECON.hits(content),
            "pairs": extract_pairs(tree, content),
        })
    return out


def verify_chunk(args):
    kind, lines = args
    out = []
    for line in lines:
        r = json.loads(line)
        if kind == "file":
            c = r["content"]
            raw = c.encode("utf-8")
            out.append({
                "repo": r["repo_name"], "license": r["license"], "bytes": len(raw),
                "sha_ok": sha256_bytes(raw) == r["sha256"], "near": near_key(c),
                "size_ok": len(raw) <= MAX_BYTES, "utf8_ok": "�" not in c and "\x00" not in c,
                "parse_ok": parse_py3(c) is not None, "contam": _DECON.hits(c), "key": (r["repo_name"], r["path"]),
            })
        else:
            text = r["prompt"] + r["completion"]
            out.append({
                "repo": r["repo_name"], "key": (r["repo_name"], r["path"]), "sha": r["sha256"],
                "sha_ok": sha256_bytes(squash(text).encode("utf-8")) == r["sha256"],
                "parse_ok": parse_py3(text) is not None, "contam": _DECON.hits(text),
            })
    return out


def repo_bucket(repo: str) -> int:
    return int(sha256_bytes(repo.encode("utf-8"))[:8], 16) % 10000


def split_of(repo: str) -> str:
    return "val" if repo_bucket(repo) < VAL_BUCKETS else "train"


def chunked(path: Path, shard: str):
    with gzip.open(path, "rt", encoding="utf-8") as f:
        buf, start, n = [], 0, 0
        for line in f:
            buf.append(line)
            n += 1
            if len(buf) == CHUNK:
                yield shard, start, buf
                buf, start = [], n
        if buf:
            yield shard, start, buf


def read_chunks(path: Path, kind: str):
    with open(path, encoding="utf-8") as f:
        buf = []
        for line in f:
            buf.append(line)
            if len(buf) == CHUNK:
                yield kind, buf
                buf = []
        if buf:
            yield kind, buf


