"""Build data/code-pretrain-v1: a permissively licensed Python pretraining corpus.

Source: codeparrot/codeparrot-clean (Python-only GitHub files, ungated, per-file
license column), pinned to one Hugging Face revision and downloaded over HTTPS.

Stages:
  1. download + sha256-verify the selected shards and the HumanEval/MBPP files
  2. filter: license allowlist, size <= 100 KiB, strict UTF-8 (no U+FFFD/NUL),
     auto-generated/minified heuristics, must parse with the Python 3 ast
  3. dedupe: exact content sha256, then a near-dupe key (comment lines dropped,
     all whitespace removed); first occurrence in (shard, row) order wins
  4. decontaminate against HumanEval, MBPP, evals/level1/coding-tasks.json and
     data/zero-composition-curriculum-v2/*.jsonl
  5. split by repository (sha256(repo_name) bucket), ~1% val
  6. extract docstring -> body pairs with ast, same split, deduped across splits
  7. re-read the outputs and write verification.json

Stdlib only. Run from the repo root:  python -I scripts/prepare_code_corpus.py
"""

