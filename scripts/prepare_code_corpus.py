def verify(args) -> None:
    cache = Path(args.cache_dir)
    items = load_blocklist(cache)
    manifest = json.loads((OUT / "manifest.json").read_text(encoding="utf-8"))
    checks: dict[str, bool] = {}
    details: dict = {}

    for name, meta in manifest["outputs"].items():
        checks[f"sha256_matches_manifest:{name}"] = sha256_file(OUT / name) == meta["sha256"]

    exact: set[str] = set()
    near: set[str] = set()
    repo_split: dict[str, str] = {}
    keys: dict[str, set] = {"train": set(), "val": set()}
    counts = collections.Counter()
    bad = collections.Counter()
    contam_hits = collections.Counter()
    with mp.Pool(args.workers, initializer=_init_worker, initargs=(items,)) as pool:
        for split in ("train", "val"):
            files = byts = 0
            for chunk in pool.imap(verify_chunk, read_chunks(OUT / f"{split}.jsonl", "file")):
                for r in chunk:
                    files += 1
                    byts += r["bytes"]
                    for k in ("sha_ok", "size_ok", "utf8_ok", "parse_ok"):
                        bad[f"{split}:{k}"] += not r[k]
                    bad[f"{split}:license"] += r["license"] not in LICENSES
                    keys[split].add(r["key"])
                    prev = repo_split.setdefault(r["repo"], split)
                    bad["repo_in_both_splits"] += prev != split
                    bad[f"{split}:split_rule"] += split_of(r["repo"]) != split
                    bad["near_dup"] += r["near"] in near
                    near.add(r["near"])
                    if r["contam"]:
                        contam_hits[f"{split}"] += 1
            counts[f"{split}_files"] = files
            counts[f"{split}_bytes"] = byts
        # exact dup check on stored hashes (cheap second read)
        for split in ("train", "val"):
            with open(OUT / f"{split}.jsonl", encoding="utf-8") as f:
                for line in f:
                    h = json.loads(line)["sha256"]
                    bad["exact_dup"] += h in exact
                    exact.add(h)
        pair_sha = {"train": set(), "val": set()}
        for split in ("train", "val"):
            n = 0
            for chunk in pool.imap(verify_chunk, read_chunks(OUT / f"docstring_pairs_{split}.jsonl", "pair")):
                for r in chunk:
                    n += 1
                    bad[f"pairs_{split}:sha_ok"] += not r["sha_ok"]
                    bad[f"pairs_{split}:parse_ok"] += not r["parse_ok"]
                    bad[f"pairs_{split}:source_file_in_split"] += r["key"] not in keys[split]
                    bad[f"pairs_{split}:dup"] += r["sha"] in pair_sha[split]
                    pair_sha[split].add(r["sha"])
                    if r["contam"]:
                        contam_hits[f"pairs_{split}"] += 1
            counts[f"pairs_{split}"] = n
    bad["pairs_cross_split"] = len(pair_sha["train"] & pair_sha["val"])

    for s in ("train", "val"):
        m = manifest["splits"][s]
        checks[f"counts_match_manifest:{s}"] = (
            counts[f"{s}_files"] == m["files"] and counts[f"{s}_bytes"] == m["content_bytes"]
            and counts[f"pairs_{s}"] == m["docstring_pairs"]
        )
    checks["no_exact_duplicates"] = bad["exact_dup"] == 0
    checks["no_near_duplicates"] = bad["near_dup"] == 0
    checks["repo_disjoint_splits"] = bad["repo_in_both_splits"] == 0
    checks["split_rule_holds"] = bad["train:split_rule"] == 0 and bad["val:split_rule"] == 0
    checks["licenses_in_allowlist"] = bad["train:license"] == 0 and bad["val:license"] == 0
    checks["sizes_within_limit"] = bad["train:size_ok"] == 0 and bad["val:size_ok"] == 0
    checks["utf8_clean"] = bad["train:utf8_ok"] == 0 and bad["val:utf8_ok"] == 0
    checks["all_files_parse_python3"] = bad["train:parse_ok"] == 0 and bad["val:parse_ok"] == 0
    checks["content_sha256_valid"] = bad["train:sha_ok"] == 0 and bad["val:sha_ok"] == 0
    checks["no_contamination_rescan"] = sum(contam_hits.values()) == 0
    checks["pairs_sha256_valid"] = bad["pairs_train:sha_ok"] == 0 and bad["pairs_val:sha_ok"] == 0
    checks["pairs_parse_python3"] = bad["pairs_train:parse_ok"] == 0 and bad["pairs_val:parse_ok"] == 0
    checks["pairs_source_in_same_split"] = bad["pairs_train:source_file_in_split"] == 0 and bad["pairs_val:source_file_in_split"] == 0
    checks["pairs_no_duplicates"] = bad["pairs_train:dup"] == 0 and bad["pairs_val:dup"] == 0 and bad["pairs_cross_split"] == 0
    total = counts["train_bytes"] + counts["val_bytes"]
    details["val_byte_fraction"] = counts["val_bytes"] / total if total else 0.0
    checks["val_fraction_about_1pct"] = 0.005 <= details["val_byte_fraction"] <= 0.02

    unparsed = {k: v for k, v in bad.items() if v}
    verification = {
        "passed": all(checks.values()),
        "manifest_sha256": sha256_file(OUT / "manifest.json"),
        "checks": checks,
        "counts": dict(counts),
        "violations": unparsed,
        "contamination_rescan_hits": dict(contam_hits),
        "details": details,
        "verified_with": {"script_sha256": sha256_file(Path(__file__)), "python": platform.python_version()},
        "training": False,
    }
    (OUT / "verification.json").write_text(json.dumps(verification, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"passed": verification["passed"], "checks": checks, "violations": unparsed}, indent=2))
    if not verification["passed"]:
        sys.exit(1)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", choices=("all", "build", "verify"), default="all")
    ap.add_argument("--num-shards", type=int, default=len(SHARDS))
    ap.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) - 1))
    ap.add_argument("--cache-dir", default=str(OUT / "source_cache"))
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    if args.stage in ("all", "build"):
        build(args)
    if args.stage in ("all", "verify"):
        verify(args)


if __name__ == "__main__":
    main()
